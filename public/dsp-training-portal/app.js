const dashboard = document.getElementById('dashboard');
const modulesGrid = document.getElementById('modulesGrid');
const presentationView = document.getElementById('presentationView');
const presentationTitle = document.getElementById('presentationTitle');
const backBtn = document.getElementById('backBtn');

const currentSlideEl = document.getElementById('currentSlide');
const slideImage = document.getElementById('slideImage');
const slideHeading = document.getElementById('slideHeading');
const slideText = document.getElementById('slideText');
const slideIndicator = document.getElementById('slideIndicator');

const prevBtn = document.getElementById('prevBtn');
const nextBtn = document.getElementById('nextBtn');

let currentModule = null;
let currentSlideIndex = 0;

// Initialize Dashboard
function initDashboard() {
  modulesGrid.innerHTML = '';
  modules.forEach(mod => {
    const card = document.createElement('div');
    card.className = 'module-card';
    card.innerHTML = `
      <div class="module-icon">${mod.icon}</div>
      <h3>${mod.title}</h3>
      <p>${mod.summary}</p>
    `;
    card.addEventListener('click', () => openPresentation(mod));
    modulesGrid.appendChild(card);
  });
}

function openPresentation(mod) {
  currentModule = mod;
  currentSlideIndex = 0;
  dashboard.style.display = 'none';
  presentationView.classList.add('active');
  presentationTitle.textContent = mod.title;
  renderSlide();
}

function closePresentation() {
  presentationView.classList.remove('active');
  dashboard.style.display = 'block';
  currentModule = null;
}

function renderSlide() {
  if (!currentModule) return;
  
  const slide = currentModule.slides[currentSlideIndex];
  
  // Fade out effect
  currentSlideEl.style.opacity = '0';
  
  setTimeout(() => {
    slideImage.src = currentModule.image;
    slideHeading.textContent = slide.heading;
    slideText.innerHTML = slide.text;
    
    slideIndicator.textContent = `${currentSlideIndex + 1} / ${currentModule.slides.length}`;
    
    prevBtn.disabled = currentSlideIndex === 0;
    
    if (currentSlideIndex === currentModule.slides.length - 1) {
      nextBtn.textContent = 'Finish';
    } else {
      nextBtn.textContent = 'Next';
    }
    
    // Fade in effect
    currentSlideEl.style.transition = 'opacity 0.3s ease';
    currentSlideEl.style.opacity = '1';
  }, 200);
}

prevBtn.addEventListener('click', () => {
  if (currentSlideIndex > 0) {
    currentSlideIndex--;
    renderSlide();
  }
});

nextBtn.addEventListener('click', () => {
  if (currentSlideIndex < currentModule.slides.length - 1) {
    currentSlideIndex++;
    renderSlide();
  } else {
    // Finish presentation
    closePresentation();
  }
});

backBtn.addEventListener('click', closePresentation);

// Startup
function handleDeepLink() {
  const urlParams = new URLSearchParams(window.location.search);
  const moduleId = urlParams.get('module');
  if (moduleId) {
    const mod = modules.find(m => m.id === moduleId);
    if (mod) {
      openPresentation(mod);
    }
  }
}

initDashboard();
handleDeepLink();
